contains

  !> Triangulate the isosurface f = isoval of a scalar field given by
  !> its values f(1:n(1),1:n(2),1:n(3)) on a uniform grid over the unit
  !> cell, point (i,j,k) at fractional coordinates ((i-1)/n(1),...).
  !> x2c is the fractional-to-Cartesian matrix and c2x its inverse. If
  !> periodic, the grid wraps around the cell boundary (crystals);
  !> otherwise the cell boundary is the domain boundary (molecules).
  !> Returns nv vertices with Cartesian coordinates xv(3,1:nv) and unit
  !> normals nrm(3,1:nv) pointing towards lower field values, and nf
  !> triangles idx(3,1:nf) (1-based vertex indices) wound
  !> counter-clockwise seen from the normal side.
  module subroutine marching_cubes(n,f,x2c,c2x,isoval,periodic,nv,xv,nrm,nf,idx)
    use types, only: realloc
    integer, intent(in) :: n(3)
    real*8, intent(in) :: f(:,:,:)
    real*8, intent(in) :: x2c(3,3)
    real*8, intent(in) :: c2x(3,3)
    real*8, intent(in) :: isoval
    logical, intent(in) :: periodic
    integer, intent(out) :: nv
    real*8, allocatable, intent(inout) :: xv(:,:)
    real*8, allocatable, intent(inout) :: nrm(:,:)
    integer, intent(out) :: nf
    integer, allocatable, intent(inout) :: idx(:,:)

    integer :: ncell(3), i, j, k, l, e, ax, icase, iv, i1w, j1w, k1w
    integer :: praw(3,8), pw(3), braw(3), ow(3), vid(12)
    integer, allocatable :: emap(:,:,:,:)
    real*8 :: vals(8), c2xt(3,3), fb, fo, den, t, xf(3), gb(3), go(3), gg(3), gnorm

    nv = 0
    nf = 0
    if (any(n < 2)) return
    if (.not.allocated(xv)) allocate(xv(3,4096))
    if (.not.allocated(nrm)) allocate(nrm(3,4096))
    if (.not.allocated(idx)) allocate(idx(3,4096))
    c2xt = transpose(c2x)

    ! number of cells per direction; the edge-to-vertex map covers the
    ! current and the next z-layer of edge base points, addressed by the
    ! parity of the (unwrapped) z index so the layers alternate with k
    if (periodic) then
       ncell = n
    else
       ncell = n - 1
    end if
    allocate(emap(3,n(1)+1,n(2)+1,2))
    emap = 0

    do k = 1, ncell(3)
       k1w = k + 1
       if (k1w > n(3)) k1w = 1 ! wraps only in the periodic case
       do j = 1, ncell(2)
          j1w = j + 1
          if (j1w > n(2)) j1w = 1
          do i = 1, ncell(1)
             i1w = i + 1
             if (i1w > n(1)) i1w = 1

             ! corner values (Bourke corner order; +1 indices wrapped)
             vals(1) = f(i,j,k)
             vals(2) = f(i1w,j,k)
             vals(3) = f(i1w,j1w,k)
             vals(4) = f(i,j1w,k)
             vals(5) = f(i,j,k1w)
             vals(6) = f(i1w,j,k1w)
             vals(7) = f(i1w,j1w,k1w)
             vals(8) = f(i,j1w,k1w)

             ! the marching cubes case for this cell
             icase = 1
             do l = 1, 8
                if (vals(l) < isoval) icase = icase + ishft(1,l-1)
             end do
             if (edgetable(icase) == 0) cycle

             ! unwrapped corner indices, for the edge-map bases
             do l = 1, 8
                praw(:,l) = (/i,j,k/) + voff(:,l)
             end do

             ! get or create the vertex on every crossed edge
             do e = 1, 12
                if (iand(edgetable(icase),ishft(1,e-1)) == 0) cycle
                ax = eaxis(e)
                braw = praw(:,ebase(e))
                iv = emap(ax,braw(1),braw(2),mod(braw(3),2)+1)
                if (iv == 0) then
                   ! interpolate the crossing along the edge
                   pw = modulo(braw-1,n) + 1
                   fb = f(pw(1),pw(2),pw(3))
                   gb = gradpt(pw)
                   ow = braw
                   ow(ax) = ow(ax) + 1
                   ow = modulo(ow-1,n) + 1
                   fo = f(ow(1),ow(2),ow(3))
                   go = gradpt(ow)
                   den = fo - fb
                   if (abs(den) > tiny(1d0)) then
                      t = min(max((isoval - fb) / den,0d0),1d0)
                   else
                      t = 0.5d0
                   end if

                   ! vertex position: fractional (from the unwrapped base
                   ! point, so seam vertices land on the far cell face),
                   ! then Cartesian
                   xf = real(braw-1,8)
                   xf(ax) = xf(ax) + t
                   xf = xf / real(n,8)

                   ! normal: interpolated gradient, to Cartesian, negated
                   ! (points towards lower f, outwards from a f > isoval
                   ! lobe, consistent with the triangle winding)
                   gg = matmul(c2xt,gb + t * (go - gb))
                   gnorm = norm2(gg)
                   if (gnorm > tiny(1d0)) then
                      gg = -gg / gnorm
                   else
                      gg = (/0d0,0d0,1d0/)
                   end if

                   nv = nv + 1
                   if (nv > size(xv,2)) then
                      call realloc(xv,3,2*nv)
                      call realloc(nrm,3,2*nv)
                   end if
                   xv(:,nv) = matmul(x2c,xf)
                   nrm(:,nv) = gg
                   iv = nv
                   emap(ax,braw(1),braw(2),mod(braw(3),2)+1) = iv
                end if
                vid(e) = iv
             end do

             ! add the triangles for this case
             l = 1
             do while (tritable(l,icase) >= 0)
                nf = nf + 1
                if (nf > size(idx,2)) call realloc(idx,3,2*nf)
                idx(1,nf) = vid(tritable(l,icase)+1)
                idx(2,nf) = vid(tritable(l+1,icase)+1)
                idx(3,nf) = vid(tritable(l+2,icase)+1)
                l = l + 3
             end do
          end do
       end do

       ! retire the finished z-layer of the edge map; its parity slot is
       ! reused by layer k+2
       emap(:,:,:,mod(k,2)+1) = 0
    end do
    deallocate(emap)

  contains
    ! Gradient of f at grid point p (wrapped indices) with respect to
    ! the fractional coordinates: central differences, wrapping in the
    ! periodic case and one-sided at the domain boundary otherwise.
    function gradpt(p) result(g)
      integer, intent(in) :: p(3)
      real*8 :: g(3)

      integer :: d, ip(3), im(3)
      real*8 :: h

      do d = 1, 3
         ip = p
         im = p
         if (periodic) then
            ip(d) = modulo(p(d),n(d)) + 1
            im(d) = modulo(p(d)-2,n(d)) + 1
            h = 0.5d0
         elseif (p(d) == 1) then
            ip(d) = 2
            h = 1d0
         elseif (p(d) == n(d)) then
            im(d) = n(d)-1
            h = 1d0
         else
            ip(d) = p(d)+1
            im(d) = p(d)-1
            h = 0.5d0
         end if
         g(d) = (f(ip(1),ip(2),ip(3)) - f(im(1),im(2),im(3))) * h * n(d)
      end do

    end function gradpt
  end subroutine marching_cubes

end submodule proc
